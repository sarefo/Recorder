// Build js/data/abc-note-index.js: the set of written pitches (MIDI numbers)
// each tune uses, so the files dialog can filter tunes by the notes they hold.
//
//   node scripts/build_note_index.mjs
//
// Only the first tune of a file (X:1) is indexed, since that is the one the app
// loads. Pitches come from the MIDI abcjs generates, so key signatures,
// accidentals and octave marks are already applied (same route as
// .claude/skills/abc-new-tune/scripts/abc_range.mjs). Run by update_data.py.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const cache = path.join(root, '.claude', 'skills', 'abc-chords', 'scripts', 'abcjs-cache.js');
const CDN = 'https://cdn.jsdelivr.net/npm/abcjs@6.4.4/dist/abcjs-basic-min.js';

if (!fs.existsSync(cache)) {
    const res = await fetch(CDN);
    if (!res.ok) throw new Error(`could not fetch abcjs: ${res.status}`);
    fs.mkdirSync(path.dirname(cache), { recursive: true });
    fs.writeFileSync(cache, await res.text());
}

globalThis.window = globalThis;
globalThis.self = globalThis;
globalThis.document = {
    createElement: () => ({ style: {}, setAttribute() {}, appendChild() {} }),
    querySelector: () => null,
};
(0, eval)(fs.readFileSync(cache, 'utf8'));
const abcjs = globalThis.ABCJS;

/** Every note-on pitch in a standard MIDI file, ignoring the percussion channel. */
function noteOns(bytes) {
    const out = [];
    let p = 0;
    const u32 = () => (bytes[p++] << 24 | bytes[p++] << 16 | bytes[p++] << 8 | bytes[p++]) >>> 0;
    const varint = () => {
        let l = 0, b;
        do { b = bytes[p++]; l = (l << 7) | (b & 0x7f); } while (b & 0x80);
        return l;
    };

    if (String.fromCharCode(...bytes.slice(0, 4)) !== 'MThd') return out;
    p = 4;
    const headerLen = u32();
    p += headerLen;

    while (p < bytes.length - 8) {
        const tag = String.fromCharCode(...bytes.slice(p, p + 4));
        p += 4;
        const len = u32();
        const end = p + len;
        if (tag !== 'MTrk') { p = end; continue; }

        let status = 0;
        while (p < end) {
            varint();                                 // delta time
            if (p >= end) break;
            if (bytes[p] & 0x80) status = bytes[p++]; // new status, or running status
            const type = status & 0xf0;
            if (status === 0xff) { p++; p += varint(); }
            else if (status === 0xf0 || status === 0xf7) p += varint();
            else if (type === 0x90) {
                const pitch = bytes[p++], vel = bytes[p++];
                if (vel > 0 && (status & 0x0f) !== 9) out.push(pitch);
            } else if (type === 0xc0 || type === 0xd0) p += 1;
            else p += 2;
        }
        p = end;
    }
    return out;
}

/** The first tune of a file: from its first X: line up to the next X: line. */
function firstTune(text) {
    const lines = text.split(/\r?\n/);
    const start = lines.findIndex(l => /^X\s*:/.test(l));
    if (start < 0) return text;
    let stop = lines.findIndex((l, i) => i > start && /^X\s*:/.test(l));
    if (stop < 0) stop = lines.length;
    return lines.slice(start, stop).join('\n');
}

function walk(dir) {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
        const full = path.join(dir, entry.name);
        return entry.isDirectory() ? walk(full) : [full];
    });
}

const abcDir = path.join(root, 'abc');
const index = {};
let failed = 0;
for (const full of walk(abcDir).filter(f => f.endsWith('.abc')).sort()) {
    const text = fs.readFileSync(full, 'utf8');
    if (!/^X:\s*\d+/m.test(text)) continue; // not listed in the app either
    const rel = path.relative(abcDir, full).replace(/\\/g, '/');
    try {
        const midi = abcjs.synth.getMidiFile(firstTune(text),
            { midiOutputType: 'binary', chordsOff: true })[0];
        const pitches = midi ? [...new Set(noteOns(Object.values(midi)))].sort((a, b) => a - b) : [];
        if (pitches.length) index[rel] = pitches;
    } catch (err) {
        console.error(`${rel}: ${err.message}`);
        failed++;
    }
}

const lines = Object.keys(index).sort().map(k => `        ${JSON.stringify(k)}: ${JSON.stringify(index[k])}`);
const js = [
    '// Auto-generated by scripts/build_note_index.mjs - do not edit manually',
    '// Written MIDI pitches used by the first tune of each file',
    'class AbcNoteIndex {',
    '    static get() {',
    '        return {',
    lines.join(',\n'),
    '        };',
    '    }',
    '}',
    '',
].join('\n');
fs.writeFileSync(path.join(root, 'js', 'data', 'abc-note-index.js'), js);
console.log(`Generated note index for ${Object.keys(index).length} ABC files` +
    (failed ? ` (${failed} failed)` : ''));
